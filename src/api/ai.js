function todayStr() {
  return new Date().toLocaleDateString("ru-RU", {
    weekday: "long", day: "numeric", month: "long", year: "numeric",
  });
}

function dateKey(d) {
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

// Собираем ПОЛНЫЙ контекст практики: клиенты, продукты, профиль специалиста,
// ближайшие события, контент-план. Используется во всех запросах к ИИ.
export async function buildFullContext() {
  const [clients, events, products, profile, content] = await Promise.all([
    getClients(), getEvents(), getProducts(), getProfile(), getContent(),
  ]);

  const clientList = (clients || []).map((c) => ({
    имя: c.name, возраст: c.age, запрос: c.request, формат: c.format,
    сессий: c.sessionsCount, статус: c.status,
    заметки: (c.sessions || []).map((s) => ({ дата: s.date, номер: s.n, заметка: s.note, динамика: s.mood })),
  }));

  const today = dateKey(new Date());
  const horizon = dateKey(new Date(Date.now() + 14 * 24 * 3600 * 1000));
  const past = dateKey(new Date(Date.now() - 45 * 24 * 3600 * 1000));
  const nearEvents = (events || [])
    .filter((e) => e.date >= past && e.date <= horizon)
    .map((e) => ({
      дата: e.date, время: e.time, название: e.title, клиент: e.clientName,
      продукт: e.productName, статус: e.status, заметка: e.note,
    }));

  const productList = (products || []).map((p) => ({
    название: p.name, длительность_мин: p.durationMin, цена: p.price, о_чём: p.about,
  }));

  return `
Ты — ИИ-ассистент внутри CRM частной практики специалиста помогающей профессии
(психолог/коуч/консультант). Сегодня: ${todayStr()}.

Твои задачи: подготовка к сессиям и анализ клиентов по заметкам; идеи и
черновики контента; бизнес-анализ и планы роста; напоминания о клиентах,
с которыми пора связаться; подбор продуктов специалиста под запрос клиента.

Правила:
- В клинических вопросах ты помощник по организации, НЕ супервизор: без диагнозов
  и директивных клинических рекомендаций, только факты из заметок и вопросы для размышления.
- В бизнес-планах не обещай гарантированный доход, не толкай к перегрузу или
  манипулятивному маркетингу; помечай допущения и риски.
- Всегда учитывай профиль специалиста и его продукты (ниже) — рекомендации
  должны опираться именно на его деятельность и сильные стороны.
- Кратко, по-русски, простым текстом без markdown-разметки.

ДАННЫЕ ПРАКТИКИ (JSON):
О специалисте: ${JSON.stringify({
    чем_занимается: profile.activity || "не заполнено",
    подход_и_особенности: profile.approach || "не заполнено",
    сильные_стороны: profile.strengths || "не заполнено",
  })}
Примеры сообщений специалиста (его стиль переписки): ${profile.voice ? JSON.stringify(profile.voice) : "не загружены"}
${profile.voice ? "ВАЖНО: когда составляешь сообщение клиенту от имени специалиста, точно имитируй его стиль из примеров — тон, длину фраз, любимые слова и обороты, эмодзи и пунктуацию. Сообщение должно быть неотличимо от написанного самим специалистом." : ""}
Продукты (услуги): ${JSON.stringify(productList)}
${productList.length === 0 ? "Продукты не заполнены — предложи заполнить их в настройках (шестерёнка), это улучшит рекомендации." : ""}
Клиенты: ${JSON.stringify(clientList)}
${clientList.length === 0 ? "Клиентов пока нет — пользователь только начинает. Помогай с общими вопросами и предложи добавить первого клиента." : ""}
События календаря (последние 45 дней и ближайшие 14): ${JSON.stringify(nearEvents)}
Контент-план: ${JSON.stringify({
    идеи: content.ideas.map((i) => i.title),
    черновики: content.drafts.map((i) => i.title),
    запланировано: content.planned.map((i) => i.title),
  })}
Финансовый учёт в приложении пока не ведётся — если нужны цифры, спроси их у
пользователя и работай с названными.
`;
}

// Совместимость со старым вызовом (контекст без async-данных не собрать,
// поэтому просто прокидываем в полный сборщик).
export async function buildContext() {
  return buildFullContext();
}

// Отправить диалог ассистенту. messages: [{role, content}].
export async function sendChat({ messages, system }) {
  const res = await fetch(`${BACKEND_URL}/api/chat`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ messages, system }),
  });
  if (!res.ok) throw new Error(`Ошибка сервера: ${res.status}`);
  const data = await res.json();
  return data.text || "";
}

// Служебный вызов: просим СТРОГО JSON и разбираем его.
async function sendJSON(prompt, system) {
  const text = await sendChat({ messages: [{ role: "user", content: prompt }], system });
  const cleaned = text.trim().replace(/^```json/i, "").replace(/^```/, "").replace(/```$/, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  return JSON.parse(cleaned.slice(start, end + 1));
}

// Расширенный анализ клиента: проблема, динамика, подходящие продукты, тактика.
export async function analyzeClient({ client, system }) {
  const prompt =
    `Проанализируй клиента «${client.name}» по заметкам специалиста и данным практики. ` +
    `Верни СТРОГО JSON без markdown, по схеме: ` +
    `{"summary": "с какой проблемой пришёл и что происходит сейчас, 2-3 предложения", ` +
    `"trend": "up|flat|down", ` +
    `"themes": ["тема1","тема2","тема3"], ` +
    `"results": ["ключевой результат/сдвиг по сессиям, 2-4 пункта"], ` +
    `"products": ["название продукта специалиста — почему подойдёт этому клиенту (только из списка продуктов; если продуктов нет — пустой массив)"], ` +
    `"approach": "как специалисту вести себя с этим клиентом, 1-2 предложения", ` +
    `"attention": ["на что особенно обращать внимание, 2-3 пункта"], ` +
    `"questions": ["вопрос к началу следующей сессии","ещё вопрос"]}. ` +
    `Без диагнозов. Опирайся только на факты из заметок.`;
  return sendJSON(prompt, system);
}

// Напоминания: сегментация клиентов (горячие/тёплые/холодные) и поводы связаться.
export async function fetchReminders(system) {
  const prompt =
    `Проанализируй клиентов и события: раздели клиентов на сегменты по давности ` +
    `контакта и активности — "горячий" (недавно был, в работе), "тёплый" (пауза ` +
    `2-4 недели или снижение частоты), "холодный" (не был месяц и больше, на паузе). ` +
    `Для тёплых и холодных предложи повод связаться, учитывая их запрос и продукты ` +
    `специалиста (например: давно не был, а у специалиста есть продукт под его проблему). ` +
    `Верни СТРОГО JSON: {"reminders":[{"client":"имя","segment":"горячий|тёплый|холодный",` +
    `"reason":"почему пора связаться, одним предложением","action":"что предложить"}]} ` +
    `— не больше 5 напоминаний, самые важные первыми. Если клиентов нет или все горячие — пустой массив.`;
  const data = await sendJSON(prompt, system);
  return Array.isArray(data.reminders) ? data.reminders : [];
}

// Идеи контента на основе практики: темы сессий, запросы клиентов, продукты.
// existingTitles — темы, которые уже были: их и похожие повторять нельзя.
export async function fetchContentIdeas(system, existingTitles = []) {
  const banned = existingTitles.length
    ? `УЖЕ БЫЛИ такие темы (не повторяй их и близкие к ним по смыслу): ${JSON.stringify(existingTitles)}. `
    : "";
  const prompt =
    `Предложи 4 НОВЫЕ идеи контента (посты, рилс, карусели) для продвижения практики. ` +
    banned +
    `Каждый раз ищи свежие ракурсы: другой формат подачи, другой сегмент аудитории, ` +
    `другая боль клиента, сезонность, личный опыт специалиста. ` +
    `Опирайся на темы из заметок о сессиях, частые запросы клиентов, продукты и ` +
    `сильные стороны специалиста. Не раскрывай личные детали клиентов — только темы. ` +
    `Верни СТРОГО JSON: {"ideas":[{"title":"заголовок идеи","format":"пост|рилс|карусель",` +
    `"why":"на чём основана идея, коротко"}]}.`;
  const data = await sendJSON(prompt, system);
  return Array.isArray(data.ideas) ? data.ideas : [];
}

