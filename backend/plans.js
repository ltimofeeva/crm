//
// ── Откуда взялись цифры ─────────────────────────────────────────────────
// Модель claude-opus-4-8 стоит $5 за 1 млн входящих токенов и $25 за 1 млн
// исходящих. В наших запросах примерно 70% токенов входящие (контекст: клиенты,
// продукты, профиль, история диалога) и 30% исходящие (ответ ассистента).
// Значит 1 млн токенов обходится примерно в:
//     0.7 × $5 + 0.3 × $25 = $11   (≈ 1 000 ₽ при курсе ~95 ₽/$)
//
// Лимиты подобраны так, чтобы расходы на ИИ занимали примерно четверть-треть
// стоимости тарифа, а остальное оставалось на сервер, эквайринг и прибыль:
//   «Помощник»      600 000 токенов ≈ $6.6  ≈ 630 ₽  из 2500 ₽  (~25%)
//   «Помощник Макс» 1 500 000 токенов ≈ $16.5 ≈ 1570 ₽ из 4800 ₽ (~33%)
//
// Ограничений два, и срабатывает то, которое исчерпается первым:
//   requests — сколько раз можно обратиться к ИИ за месяц (защита от «много
//              мелких запросов»);
//   tokens   — сколько всего токенов можно израсходовать (защита от «мало, но
//              очень тяжёлых запросов» — например, разбор большой базы клиентов).
// ─────────────────────────────────────────────────────────────────────────

